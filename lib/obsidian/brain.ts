/**
 * Obsidian Brain — the project's persistent knowledge layer.
 *
 * Each department writes to its section after runs. A nightly consolidator
 * compresses the day's learnings into a digest. A morning briefing reads
 * the vault and primes all agents with relevant context.
 *
 * Structure:
 *   ~/Obsidian/Nexorra/
 *     Daily/           — Daily digests (one per day)
 *     Leads/           — Per-lead notes (synced from DB)
 *     Clients/         — Per-client profiles
 *     Research/         — Market research, competitor analysis
 *     Engineering/      — ADRs, bug reports, architecture decisions
 *     Marketing/        — Campaign results, copy performance, outreach patterns
 *     Experiments/      — A/B test results, hypothesis outcomes
 *     Briefings/        — Morning briefing summaries (read by all agents)
 *     Index.md          — Master index with links to everything
 */

import fs from 'fs/promises';
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'fs';
import path from 'path';
import os from 'os';

const VAULT = path.join(os.homedir(), 'Obsidian', 'Nexorra');

const SECTIONS = [
  'Daily', 'Leads', 'Clients', 'Research', 'Engineering',
  'Marketing', 'Experiments', 'Briefings',
] as const;

type Section = typeof SECTIONS[number];

function ensureDir(dir: string) {
  mkdirSync(dir, { recursive: true });
}

function today(): string {
  return new Date().toISOString().slice(0, 10);
}

function now(): string {
  return new Date().toISOString().slice(0, 19).replace('T', ' ');
}

// ─── Writing ──────────────────────────────────────────────────────────────────

/**
 * Append content to a section note. Creates the file if it doesn't exist.
 * Used by agents to log findings, decisions, results after each run.
 */
export function appendToSection(
  section: Section,
  filename: string,
  content: string,
  heading?: string
): void {
  ensureDir(path.join(VAULT, section));
  const filepath = path.join(VAULT, section, filename.endsWith('.md') ? filename : `${filename}.md`);

  const timestamp = now();
  const block = heading
    ? `\n## ${heading} (${timestamp})\n\n${content}\n`
    : `\n### ${timestamp}\n\n${content}\n`;

  if (existsSync(filepath)) {
    const existing = readFileSync(filepath, 'utf-8');
    writeFileSync(filepath, existing + block, 'utf-8');
  } else {
    writeFileSync(filepath, `# ${filename.replace('.md', '')}\n${block}`, 'utf-8');
  }
}

/**
 * Write a complete section note (overwrites).
 */
export function writeSection(section: Section, filename: string, content: string): void {
  ensureDir(path.join(VAULT, section));
  const filepath = path.join(VAULT, section, filename.endsWith('.md') ? filename : `${filename}.md`);
  writeFileSync(filepath, content, 'utf-8');
}

